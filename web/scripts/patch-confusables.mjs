// 적용
let patched = 0;
for (const item of kanji) {
  if (item.confusables && item.confusables.length > 0) continue;
  const p = patches[item.hanja];
  if (!p) continue;
  // kanji.json에 있는 것만 필터
  const valid = p.filter(c => hanjaSet.has(c) && c !== item.hanja);
  if (valid.length === 0) continue;
  item.confusables = valid;
  patched++;
}

writeFileSync(KANJI_PATH, JSON.stringify(kanji, null, 2) + '\n');
console.log(`✅ ${patched}자 confusables 패치`);

const remaining = kanji.filter(x => !x.confusables || x.confusables.length === 0);
